"""Colosseum battle-sequence wire format, derived from the matching interpreter.

This is a data language: command bytes dispatch through lbl_8027A00C and operands
are big-endian scalars or encoded addresses. It does not emit native instructions.
Only commands used by the reconstructed programs are supported. Every schema names
the existing C handler that establishes its operand roles and instruction stride.
command_c8 and command_eb keep handler-derived names: their handlers establish the
operand layout, but not yet a confident gameplay meaning.

Compatibility behavior is deliberate:
* print_selection_message_legacy stores two operand bytes, but wsCmd11 reads a
  32-bit message including two bytes of lookahead and advances by three bytes.
* animate_selected_condition ignores its second operand byte and compares its
  following u32 numerically; that value is not a pointer.
* copy_target_stat_stages never reads its encoded target. The address still has
  its original relocation, but it is not an executable control-flow edge.
* apply_intimidate ignores its four-byte zero operand.
See docs/recon/battle_script_source.md for source evidence and validation.
"""

from dataclasses import dataclass


